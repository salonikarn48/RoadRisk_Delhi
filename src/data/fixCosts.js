export function getHotspotFixConfig(hotspotIdOrName) {
  if (HOTSPOT_FIX_COSTS[hotspotIdOrName]) {
    return HOTSPOT_FIX_COSTS[hotspotIdOrName];
  }
  const clean = hotspotIdOrName.toLowerCase().trim();
  for (const [key, val] of Object.entries(HOTSPOT_FIX_COSTS)) {
    if (
      key.toLowerCase() === clean ||
      val.hotspotName.toLowerCase() === clean ||
      val.hotspotName.toLowerCase().includes(clean)
    ) {
      return val;
    }
  }
  return null;
}
